const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vendor = fs.readFileSync(path.join(__dirname, 'vendor/fflate.min.js'), 'utf8');
const hash = crypto.createHash('sha256').update(vendor).digest('hex');
if (hash !== 'c3b34f2e9f5e74d4d7d64e01cac7a0c01954c6c406414d42185c7b53d6875ddf') throw new Error('unexpected fflate source');
const patch = fs.readFileSync(path.join(__dirname, 'usercenter.patch.js'), 'utf8');
const ads = fs.readFileSync(path.join(__dirname, 'umetrip_ads.js'), 'utf8');
const packageRecord = ads.match(/const usercenterPackage = \{[\s\S]*?\n\};/);
if (!packageRecord) throw new Error('missing shared package metadata');
const license = fs.readFileSync(path.join(__dirname, 'vendor/LICENSE.fflate'), 'utf8');
const output = '/* Generated by build-usercenter.cjs. Patch: GPL-3.0; fflate 0.8.2: MIT, Copyright (c) 2023 Arjun Barrett. See LICENSE and vendor/LICENSE.fflate. */\n' +
  '/* Bundled fflate license:\n' + license + '\n*/\n' +
  'const umetripZip = (() => { const self = {}; const module = undefined, exports = undefined, define = undefined;\n' + vendor + '\nreturn self.fflate; })();\n' + packageRecord[0] + '\n' + patch;
fs.writeFileSync(path.join(__dirname, 'usercenter.js'), output);
